// ════════════════════════════════════════════════════════════
// ไฟล์ชื่อ — api.ts การตั้งค่า URL ของ API (API URL Configuration)
// ════════════════════════════════════════════════════════════
// หน้าที่ของไฟล์: 
// กำหนด URL ของ API แบบอัตโนมัติตามแพลตฟอร์มที่กำลังรันแอปพลิเคชัน
// เพื่อให้สามารถเชื่อมต่อกับ backend ได้ถูกต้องไม่ว่าจะทดสอบบนคอมพิวเตอร์, 
// เครื่องจำลอง (Emulator/Simulator), มือถือจริง หรือใช้งานบนเซิร์ฟเวอร์จริง (VPS)

import { Platform } from 'react-native';

// ────────────────────────────────────────
// การตั้งค่า Environment
// ────────────────────────────────────────
// ตัวแปรนี้ทำหน้าที่กำหนดว่าจะเชื่อมต่อฐานข้อมูลในเครื่อง (Local) หรือบนคลาวด์ (VPS)
// - true = ใช้เซิร์ฟเวอร์จริง (VPS) สำหรับ production หรือทดสอบกับข้อมูลจริง
// - false = ใช้ backend ในเครื่อง สำหรับพัฒนาและทดสอบ
// ทำไมต้องมี: เพื่อให้สลับไปมาระหว่างเซิร์ฟเวอร์ทดสอบกับเซิร์ฟเวอร์จริงได้ง่ายโดยไม่ต้องแก้โค้ดหลายที่
// ใช้ IP ที่เหมาะกับแต่ละ platform
// - Android Emulator: 10.0.2.2 จะชี้ไปที่ localhost ของเครื่องคอมพิวเตอร์
// - Web / iOS Simulator: ใช้ localhost ได้ปกติ
// - เครื่องจริง (มือถือ): ใช้ IP จริงของคอมพิวเตอร์ที่รัน server
// ปรับค่าตรงนี้เพื่อเลือกว่าจะต่อฐานข้อมูลในเครื่อง (Local) หรือบนคลาวด์ (VPS)
const USE_VPS = true; // false = ใช้ backend ในเครื่อง / true = เซิร์ฟเวอร์จริง VPS

// ════════════════════════════════════════════════════════════
// ฟังก์ชัน getBaseUrl — คืนค่า API URL ตามแพลตฟอร์ม
// ════════════════════════════════════════════════════════════
// ขั้นตอนการทำงาน:
// 1. ตรวจสอบ USE_VPS → ถ้า true จะคืนค่า IP ของเซิร์ฟเวอร์จริงทันที
// 2. ถ้าไม่ได้ใช้ VPS, ตรวจสอบว่าเป็นเว็บเบราว์เซอร์หรือไม่ (window.location) → 
//    ถ้าใช่ ให้ใช้ hostname ปัจจุบัน หรือ localhost
// 3. ตรวจสอบว่าเป็น Android หรือไม่ → ถ้าใช่ คืนค่า IP วงแลนในเครื่อง เพราะ Android Emulator 
//    (หรือเครื่องจริงที่ต่อ Wi-Fi) จะมอง localhost (127.0.0.1) เป็นเครื่องจำลองเอง ไม่ใช่คอมพิวเตอร์ที่รัน backend
// 4. กรณีอื่นๆ (เช่น iOS Simulator) → คืนค่า localhost
const getBaseUrl = () => {
    if (USE_VPS) {
        return 'http://119.59.102.161:3018/api'; // IP และ Port บนเซิร์ฟเวอร์จริงของคุณ
    }

    if (typeof window !== 'undefined' && window.location) {
        // หากเปิดผ่านเบราว์เซอร์ Local
        const hostname = window.location.hostname;
        if (hostname === 'localhost' || hostname === '127.0.0.1') {
            return 'http://localhost:3000/api';
        }
        return `http://${hostname}:3000/api`;
    }
    if (Platform.OS === 'android') {
        return 'http://192.168.110.122:3000/api'; // IP วงแลนในเครื่อง
    }
    return 'http://localhost:3000/api';
};

export const API_BASE_URL = getBaseUrl();
